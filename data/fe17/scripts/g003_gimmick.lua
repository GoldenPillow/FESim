	end

	TerrainSetEnd()

end

function Copy( orig )

	local copy = {}

	for key, value in pairs(orig) do
		copy[key] = { x = value.x, z = value.z, terrain = value.terrain }

	end

	return copy

end

function SortInAsc( list )

	table.sort( list,
				function( a, b )
					return ( a.x > b.x )
				end
				)
end

function SortInDesc( list )

	table.sort( list,
				function( a, b )
					return ( a.x < b.x )
				end
				)
end
